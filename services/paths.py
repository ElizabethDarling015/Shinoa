"""
Единое персистентное хранилище для файлов, которые должны переживать не
только рестарт самого бота, но и перезагрузку хоста: registry.json,
settings.json, пары прокси+куки (proxy_pairs.py), status.json/.log отдельных
запущенных потоков.

Раньше всё это лежало в tempfile.gettempdir() (/tmp) — разумно выглядело для
"временных" status.json/.log конкретного запуска, но в ту же папку по
инерции легли и по-настоящему постоянные данные (пул пар прокси+куки, общий
реестр активных потоков). А /tmp на многих системах (в т.ч. эта VM —
подтверждено экспериментально: `virsh destroy`+`start` стирает файл, обычный
рестарт процесса бота — нет) чистится самой ОС при полной перезагрузке хоста
через systemd-tmpfiles-setup или аналог — НЕЗАВИСИМО от того, что это самый
обычный раздел на диске, а не tmpfs в памяти. Отсюда была потеря пары
прокси+куки+UA после перезагрузки VM.

Вынесено в отдельный модуль БЕЗ каких-либо внутренних импортов специально:
и service_manager.py, и proxy_pairs.py должны иметь возможность взять этот
путь, а service_manager.py сам импортирует proxy_pairs — общий модуль без
зависимостей от них обоих исключает циклический импорт.
"""
from pathlib import Path

# Персистентный каталог РЯДОМ С САМИМ РЕПОЗИТОРИЕМ (переживает перезагрузку
# хоста), а не во временной ФС. Добавь его в .gitignore, если ещё не добавлен —
# это рантайм-данные конкретного развёртывания, не часть кода.
STATUS_DIR = Path(__file__).resolve().parent.parent / "var" / "shinoa_service_status"
STATUS_DIR.mkdir(parents=True, exist_ok=True)
